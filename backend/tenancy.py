# ── resolution (cached) ──────────────────────────────────────────────────────
# Small in-process caches. Cleared on provision / status change. A production
# deployment would back these with Redis (Phase 4); for now a lookup miss does a
# short-lived connection.
_CACHE = {}            # slug -> (schema, status)
_SCHEMA_STATUS = {}    # schema -> status
_HOST_CACHE = {}       # custom domain (host) -> (schema, status)
_MODULES_CACHE = {}    # schema -> effective module set (or None)


def _lookup_by_slug(slug: str):
    if slug in _CACHE:
        return _CACHE[slug]
    try:
        raw = _connect()
    except Exception:
        return None
    try:
        with raw.cursor() as cur:
            cur.execute("SELECT schema_name, status FROM public.tenants WHERE slug=%s", (slug,))
            row = cur.fetchone()
    except Exception:
        return None
    finally:
        raw.close()
    if not row:
        return None
    res = (row["schema_name"], row["status"])
    _CACHE[slug] = res
    _SCHEMA_STATUS[row["schema_name"]] = row["status"]
    return res


def _lookup_by_host(host: str):
    """Resolve a full hostname (custom domain) to ``(schema, status)`` via the
    verified entries in public.tenant_domains, or None. Cached."""
    if host in _HOST_CACHE:
        return _HOST_CACHE[host]
    try:
        raw = _connect()
    except Exception:
        return None
    try:
        with raw.cursor() as cur:
            cur.execute(
                "SELECT t.schema_name, t.status "
                "FROM public.tenant_domains d "
                "JOIN public.tenants t ON t.schema_name = d.schema_name "
                "WHERE d.domain = %s AND d.verified = 1",
                (host,))
            row = cur.fetchone()
    except Exception:
        return None
    finally:
        raw.close()
    if not row:
        return None
    res = (row["schema_name"], row["status"])
    _HOST_CACHE[host] = res
    return res


def _schema_status(schema: str):
    """Return the tenant status ('active' | 'suspended') for a schema, or None if
    no such tenant exists. Cached."""
    if schema in _SCHEMA_STATUS:
        return _SCHEMA_STATUS[schema]
    try:
        raw = _connect()
    except Exception:
        return None
    try:
        with raw.cursor() as cur:
            cur.execute("SELECT status FROM public.tenants WHERE schema_name=%s", (schema,))
            row = cur.fetchone()
    except Exception:
        return None
    finally:
        raw.close()
    if not row:
        return None
    _SCHEMA_STATUS[schema] = row["status"]
    return row["status"]


def _schema_from_cookie(cookie_header: str):
    if not cookie_header:
        return None
    jar = SimpleCookie()
    try:
        jar.load(cookie_header)
    except Exception:
        return None
    if COOKIE_NAME not in jar:
        return None
    try:
        # Signature-verified, but ignore expiry here — expiry is enforced later by
        # require_auth. We only need the (authentic) schema claim to route the DB.
        payload = jwt.decode(jar[COOKIE_NAME].value, SECRET_KEY,
                             algorithms=[ALGORITHM], options={"verify_exp": False})
    except Exception:
        return None
    schema = payload.get("schema")
    return schema if valid_schema_name(schema) else None


def _subdomain(host: str):
    parts = host.split(".")
    if len(parts) >= 3 and parts[0] not in ("www", "app", "api", "admin"):
        return parts[0]
    return None


def resolve_tenant_from_scope(scope):
    """Resolve the request's tenant. Returns ``(schema, status)`` or ``None``.
    Priority: signed JWT ``schema`` claim → ``X-Tenant`` header → host subdomain."""
    headers = {k.decode("latin1").lower(): v.decode("latin1")
               for k, v in scope.get("headers", [])}

    # 1) Authenticated request → the signed JWT's schema claim is authoritative.
    schema = _schema_from_cookie(headers.get("cookie", ""))
    if schema:
        status = _schema_status(schema)
        if status:
            return (schema, status)

    # 2) Explicit X-Tenant header (login form / API clients).
    slug = headers.get("x-tenant", "").strip().lower()
    if valid_slug(slug):
        found = _lookup_by_slug(slug)
        if found:
            return found

    host = headers.get("host", "").split(":")[0].strip().lower().rstrip(".")

    # 3) Custom domain — exact Host match against a verified tenant domain
    #    (erp.clientco.com → tenant). Checked before the subdomain scheme so a
    #    client's own domain takes precedence.
    if host:
        found = _lookup_by_host(host)
        if found:
            return found

    # 4) Host subdomain (acme.erp.app → 'acme').
    sub = _subdomain(host)
    if sub and valid_slug(sub):
        found = _lookup_by_slug(sub)
        if found:
            return found

    return None  # unresolved → get_db falls back to `public` (no business tables)


class TenantMiddleware:
    """Pure-ASGI middleware: resolve the request's tenant schema and stash it in
    the ContextVar so get_db can pin the connection's search_path. A request that
    resolves to a SUSPENDED tenant is blocked with 402. Inert unless
    TENANCY=schema."""

    def __init__(self, app):
        self.app = app

    async def __call__(self, scope, receive, send):
        if scope.get("type") != "http" or not IS_SCHEMA_TENANCY:
            await self.app(scope, receive, send)
            return
        resolved = resolve_tenant_from_scope(scope)
        if resolved is not None and resolved[1] != "active":
            from starlette.responses import JSONResponse
            await JSONResponse(
                {"detail": "This workspace is suspended. Please contact support."},
                status_code=402)(scope, receive, send)
            return
        schema = resolved[0] if resolved else None
        token = set_current_schema(schema)
        try:
            await self.app(scope, receive, send)
        finally:
            reset_current_schema(token)
