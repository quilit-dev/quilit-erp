def verify_tenant_domain(domain: str) -> dict:
    """Check the DNS TXT record and mark the domain verified if the token matches.
    Returns {domain, verified}."""
    from utils import _now
    domain = (domain or "").strip().lower().rstrip(".")
    raw = _connect()
    try:
        ensure_tenant_domains_catalog(raw)
        with raw.cursor() as cur:
            cur.execute("SELECT verify_token FROM public.tenant_domains WHERE domain=%s", (domain,))
            row = cur.fetchone()
            if not row:
                raise ValueError(f"Domain not found: {domain!r}")
            token = row["verify_token"]
            txt = _resolve_txt(f"{VERIFY_TXT_PREFIX}.{domain}")
            ok = any(token == t.strip() for t in txt)
            if ok:
                cur.execute(
                    "UPDATE public.tenant_domains SET verified=1, verified_at=%s WHERE domain=%s",
                    (_now(), domain))
        raw.commit()
    finally:
        raw.close()
    _HOST_CACHE.pop(domain, None)
    return {"domain": domain, "verified": bool(ok)}


def is_verified_domain(host: str) -> bool:
    """True if `host` is a known, verified tenant domain. Used by the on-demand
    TLS gate so a certificate is only ever issued for a host we recognise."""
    host = (host or "").strip().lower().rstrip(".")
    if not host:
        return False
    return _lookup_by_host(host) is not None


