def _gen_password(n: int = 16) -> str:
    import secrets
    import string
    alphabet = string.ascii_letters + string.digits + "!@#$%^&*"
    return "".join(secrets.choice(alphabet) for _ in range(n))

# slug → schema. Slugs are lower-case alnum/underscore so the derived schema name
# is always a safe identifier.
_SLUG_RE = re.compile(r"^[a-z0-9][a-z0-9_]{0,40}$")


def schema_for_slug(slug: str) -> str:
    return "tenant_" + slug


def valid_slug(slug) -> bool:
    return isinstance(slug, str) and bool(_SLUG_RE.match(slug))


# ── tenant catalog (lives in public) ─────────────────────────────────────────

def _connect():
    import psycopg
    from psycopg.rows import dict_row
    from database import _pg_dsn
    return psycopg.connect(_pg_dsn(), row_factory=dict_row)


# Provisioning profile carried per tenant. Kept in the shared public catalog
# (not inside the tenant schema) because the Control Center has to read across
# every customer without connecting to each schema in turn.
#
# `modules` stores the SELECTED set only. The effective set is always the
# dependency closure of this, computed at read time by capabilities.resolve(),
# so a plan can never be stored in a state that does not work.
_TENANT_COLUMNS = (
    "industry        TEXT",
    "language        TEXT DEFAULT 'en'",
    "currency        TEXT DEFAULT 'USD'",
    "contact_email   TEXT",
    "contact_phone   TEXT",
    "company_address TEXT",
    "tax_number      TEXT",
    "modules         TEXT",          # comma-separated selected module keys
    "max_users       INTEGER",       # licensed seats; NULL = unlimited
    "trial_ends_at   TEXT",          # ISO date; NULL = not a trial
    "license_expires_at TEXT",       # ISO date; NULL = perpetual
    "notes           TEXT",
    "updated_at      TEXT",
)


def ensure_tenants_catalog(raw) -> None:
    with raw.cursor() as cur:
        cur.execute("""
            CREATE TABLE IF NOT EXISTS public.tenants (
                id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                slug        TEXT UNIQUE NOT NULL,
                schema_name TEXT UNIQUE NOT NULL,
                name        TEXT,
                status      TEXT NOT NULL DEFAULT 'active',   -- 'active' | 'suspended'
                plan        TEXT NOT NULL DEFAULT 'standard',
                created_at  TEXT NOT NULL
            )
        """)
        # Additive migration. New installs get these from the CREATE above on
        # the next release; existing catalogs are upgraded in place. ADD COLUMN
        # IF NOT EXISTS keeps this idempotent, so it runs safely on every boot.
        for ddl in _TENANT_COLUMNS:
            cur.execute(f"ALTER TABLE public.tenants ADD COLUMN IF NOT EXISTS {ddl}")
    raw.commit()


def _schema_initialized(raw, schema: str) -> bool:
    with raw.cursor() as cur:
        cur.execute("SELECT to_regclass(%s) AS reg", (f"{schema}.schema_migrations",))
        if cur.fetchone()["reg"] is None:
            return False
        cur.execute(f'SELECT count(*) AS n FROM "{schema}".schema_migrations')
        return cur.fetchone()["n"] > 0


def provision_tenant(slug: str, name: str = None, plan: str = "standard",
                     admin_password: str = None, profile: dict = None) -> dict:
    """Create and seed a new tenant schema, and register it in the catalog.

    Idempotent on the schema/catalog, but each call resets the tenant admin's
    password to a freshly generated (or supplied) value and returns it ONCE so the
    operator can hand the new customer their first login. Returns the catalog row
    plus ``admin_username`` / ``admin_password``.
    """
    from utils import _now
    from db_compat import CompatConn
    from dialect import get_dialect
    from database import (_apply_pg_baseline, _ensure_pg_post_baseline,
                          _seed_roles_and_admin)

    if not valid_slug(slug):
        raise ValueError(f"Invalid tenant slug: {slug!r} (use a-z, 0-9, _).")
    schema = schema_for_slug(slug)
    admin_password = admin_password or _gen_password()

    raw = _connect()
    try:
        ensure_tenants_catalog(raw)
        with raw.cursor() as cur:
            cur.execute(f'CREATE SCHEMA IF NOT EXISTS "{schema}"')
        raw.commit()

        # Point the session at the new schema so the baseline's unqualified DDL
        # and the shared seeding land inside it (not public).
        with raw.cursor() as cur:
            cur.execute(f'SET search_path TO "{schema}", public')
        if not _schema_initialized(raw, schema):
            _apply_pg_baseline(raw)                 # tables/indexes/ledger → tenant schema
        # The baseline is a SQUASHED snapshot; every migration added after it
        # was generated still has to run. _init_db_postgres does both steps —
        # provisioning previously did only the first, so each tenant schema was
        # born missing every later column (branch_id and friends) and every
        # query touching one returned a 500. Idempotent, so it is also the
        # upgrade path for schemas provisioned before this fix.
        _ensure_pg_post_baseline(raw)
        conn = CompatConn(raw, get_dialect("postgres"))
        _seed_roles_and_admin(conn)                 # roles/permissions/admin → tenant schema
        # Set a known initial admin password (the seeding's own random one is never
        # surfaced); force a reset on first login.
        conn.execute("UPDATE users SET password_hash=?, must_change_password=1 "
                     "WHERE username='admin'", (hash_password(admin_password),))
        # This workspace is already set up: an admin exists and its password has
        # just been handed to the owner. Without this the flag stayed "0" and
        # the UNAUTHENTICATED first-run wizard (/api/settings/complete-setup)
        # remained open forever on the tenant's subdomain — anyone who reached
        # it could set the admin password and own the customer's books. The
        # endpoint refuses in multi-tenant mode regardless; this keeps the
        # stored state honest too.
        conn.execute(
            "INSERT INTO settings (key, value) VALUES ('setup_complete', '1') "
            "ON CONFLICT (key) DO UPDATE SET value = '1'")
        conn.commit()

        with raw.cursor() as cur:
            cur.execute(
                "INSERT INTO public.tenants (slug, schema_name, name, status, plan, created_at) "
                "VALUES (%s, %s, %s, 'active', %s, %s) ON CONFLICT (slug) DO NOTHING",
                (slug, schema, name or slug, plan, _now()))
            # Profile fields are written separately so provisioning stays
            # backward compatible: an older caller that passes no profile
            # provisions exactly as before.
            if profile:
                _apply_profile(cur, slug, profile)
            cur.execute("SELECT * FROM public.tenants WHERE slug=%s", (slug,))
            row = cur.fetchone()
        raw.commit()
    finally:
        raw.close()

    _CACHE.pop(slug, None)               # refresh any cached lookup
    _SCHEMA_STATUS.pop(schema, None)
    _MODULES_CACHE.pop(schema, None)
    _LICENCE_CACHE.pop(schema, None)
    _LICENCE_CACHE.pop(("seats", schema), None)
    return {**dict(row), "admin_username": "admin", "admin_password": admin_password}


# Fields the Control Center may write. Anything not listed is ignored rather
# than rejected, so an older console posting an unknown key cannot 500 a
# provisioning run.
_PROFILE_FIELDS = (
    "name", "plan", "industry", "language", "currency", "contact_email",
    "contact_phone", "company_address", "tax_number", "max_users",
    "trial_ends_at", "license_expires_at", "notes",
)


def _apply_profile(cur, slug: str, profile: dict) -> None:
    """UPDATE the catalog row from a profile dict. Caller owns the transaction."""
    # `_now` is imported per-function throughout this module (utils imports
    # database, so a module-level import would create a cycle).
    from utils import _now
    sets, params = [], []
    for field in _PROFILE_FIELDS:
        if field in profile and profile[field] is not None:
            sets.append(f"{field} = %s")
            params.append(profile[field])
    # `modules` is normalised: store the SELECTED keys, deduplicated and
    # ordered, so the row is stable and diffable. The effective set is always
    # recomputed from this by capabilities.resolve().
    if "modules" in profile and profile["modules"] is not None:
        import capabilities
        selected = sorted({m.strip() for m in profile["modules"] if str(m).strip()
                           and capabilities.known_module(str(m).strip())})
        sets.append("modules = %s")
        params.append(",".join(selected))
    if not sets:
        return
    sets.append("updated_at = %s")
    params.append(_now())
    params.append(slug)
    cur.execute(f"UPDATE public.tenants SET {', '.join(sets)} WHERE slug = %s", params)


def update_tenant(slug: str, profile: dict) -> dict:
    """Edit a tenant's provisioning profile. Returns the updated catalog row."""
    if not valid_slug(slug):
        raise ValueError(f"Invalid tenant slug: {slug!r}")
    raw = _connect()
    try:
        ensure_tenants_catalog(raw)
        with raw.cursor() as cur:
            _apply_profile(cur, slug, profile)
            cur.execute("SELECT * FROM public.tenants WHERE slug=%s", (slug,))
            row = cur.fetchone()
        raw.commit()
    finally:
        raw.close()
    _CACHE.pop(slug, None)
    # _MODULES_CACHE is keyed by SCHEMA, not slug — popping the slug here was a
    # no-op, so a licence change never took effect in this process. Every other
    # invalidation site already used the schema.
    _MODULES_CACHE.pop(schema_for_slug(slug), None)
    _LICENCE_CACHE.pop(schema_for_slug(slug), None)
    _LICENCE_CACHE.pop(("seats", schema_for_slug(slug)), None)
    return dict(row) if row else None


def delete_tenant(slug: str) -> dict:
    """Permanently decommission a tenant: drop its schema and forget it.

    IRREVERSIBLE. Everything the customer owns lives in their schema, so this
    destroys their ledger, documents metadata, users and audit trail with no
    undo. Suspending (`set_tenant_status`) is almost always what you want -
    it blocks access, keeps the data, and can be reversed by flipping the
    status back. Delete is for decommissioning a cancelled or mistaken
    tenant, and the API requires an explicit confirmation to reach it.

    Returns a summary of what was removed.
    """
    if not valid_slug(slug):
        raise ValueError(f"Invalid tenant slug: {slug!r}")
    schema = schema_for_slug(slug)
    # Defence in depth: schema_for_slug is the only source of this identifier
    # and valid_slug has already constrained it, but the name is interpolated
    # into DDL (it cannot be a bind parameter), so re-check before use.
    if not valid_schema_name(schema):
        raise ValueError(f"Refusing to drop unsafe schema name: {schema!r}")

    raw = _connect()
    try:
        ensure_tenants_catalog(raw)
        ensure_tenant_domains_catalog(raw)
        with raw.cursor() as cur:
            cur.execute("SELECT slug, name FROM public.tenants WHERE slug=%s", (slug,))
            row = cur.fetchone()
            if not row:
                raise ValueError(f"No such tenant: {slug!r}")
            cur.execute(f'DROP SCHEMA IF EXISTS "{schema}" CASCADE')
            cur.execute("DELETE FROM public.tenant_domains WHERE slug=%s", (slug,))
            domains_removed = cur.rowcount or 0
            cur.execute("DELETE FROM public.tenants WHERE slug=%s", (slug,))
        raw.commit()
    finally:
        raw.close()

    _CACHE.pop(slug, None)
    _SCHEMA_STATUS.pop(schema, None)
    _MODULES_CACHE.pop(schema, None)
    _LICENCE_CACHE.pop(schema, None)
    _LICENCE_CACHE.pop(("seats", schema), None)
    _HOST_CACHE.clear()                  # any domain pointing here is now gone
    return {"slug": slug, "name": row.get("name"), "schema": schema,
            "domains_removed": domains_removed, "deleted": True}


def list_tenant_users(slug: str) -> list:
    """User accounts inside a tenant, for the Control Center's admin tools."""
    if not valid_slug(slug):
        raise ValueError(f"Invalid tenant slug: {slug!r}")
    schema = schema_for_slug(slug)
    if not valid_schema_name(schema):
        raise ValueError(f"Unsafe schema name: {schema!r}")
    raw = _connect()
    try:
        with raw.cursor() as cur:
            cur.execute(f'SET search_path TO "{schema}", public')
            cur.execute("SELECT id, username, full_name, is_active, "
                        "       must_change_password, last_login "
                        "FROM users ORDER BY id")
            return [dict(r) for r in cur.fetchall()]
    except Exception as e:
        raise ValueError(f"Could not read users for {slug!r}: {e}")
    finally:
        raw.close()


def reset_tenant_user_password(slug: str, username: str,
                               password: str = None) -> dict:
    """Reset one user's password inside a tenant. Returns it ONCE.

    Forces must_change_password, so the operator's temporary credential stops
    working the moment the customer signs in — a vendor should never hold a
    usable login to a customer's books.
    """
    from utils import _now
    if not valid_slug(slug):
        raise ValueError(f"Invalid tenant slug: {slug!r}")
    schema = schema_for_slug(slug)
    if not valid_schema_name(schema):
        raise ValueError(f"Unsafe schema name: {schema!r}")
    username = (username or "").strip()
    if not username:
        raise ValueError("Username is required.")
    password = password or _gen_password()

    raw = _connect()
    try:
        with raw.cursor() as cur:
            cur.execute(f'SET search_path TO "{schema}", public')
            cur.execute("UPDATE users SET password_hash=%s, must_change_password=1 "
                        "WHERE username=%s RETURNING id, username",
                        (hash_password(password), username))
            row = cur.fetchone()
            if not row:
                raise ValueError(f"No user {username!r} in {slug!r}.")
            # Kill any live session for that user so an attacker holding a
            # stolen cookie cannot outlive the reset.
            try:
                cur.execute("UPDATE user_sessions SET revoked=1 WHERE user_id=%s",
                            (row["id"],))
            except Exception:
                pass
        raw.commit()
    finally:
        raw.close()
    return {"slug": slug, "username": row["username"], "password": password,
            "must_change_password": True}


def factory_reset(slug: str) -> dict:
    """Wipe a tenant's DATA but keep the business itself.

    IRREVERSIBLE for the data. Implemented as drop-and-reprovision rather than
    truncating tables: the schema has dozens of tables bound by foreign keys,
    and any hand-maintained TRUNCATE order silently rots the moment a table is
    added. Re-provisioning reuses the same code path that builds a brand-new
    tenant, so a reset workspace is bit-for-bit what a fresh one looks like.

    KEPT (the catalog row is never touched): name, plan, licensed modules,
    industry, language, currency, contact details, licence dates and any
    verified custom domains.

    LOST: every business record - clients, invoices, the ledger, documents,
    users beyond the rebuilt admin, and the audit trail.

    Returns the fresh admin credentials, since the previous ones are gone
    with the schema.
    """
    if not valid_slug(slug):
        raise ValueError(f"Invalid tenant slug: {slug!r}")
    schema = schema_for_slug(slug)
    if not valid_schema_name(schema):
        raise ValueError(f"Refusing to drop unsafe schema name: {schema!r}")

    raw = _connect()
    try:
        ensure_tenants_catalog(raw)
        with raw.cursor() as cur:
            cur.execute("SELECT slug, name, plan FROM public.tenants WHERE slug=%s", (slug,))
            row = cur.fetchone()
            if not row:
                raise ValueError(f"No such tenant: {slug!r}")
            # Drop only the tenant's own schema. The public catalog - and with
            # it the customer's identity, licence and domains - is untouched.
            cur.execute(f'DROP SCHEMA IF EXISTS "{schema}" CASCADE')
        raw.commit()
    finally:
        raw.close()

    _CACHE.pop(slug, None)
    _SCHEMA_STATUS.pop(schema, None)
    _MODULES_CACHE.pop(schema, None)
    _LICENCE_CACHE.pop(schema, None)
    _LICENCE_CACHE.pop(("seats", schema), None)

    # Rebuild via the normal provisioning path; ON CONFLICT DO NOTHING means
    # the surviving catalog row keeps its profile.
    result = provision_tenant(slug, row.get("name"), row.get("plan") or "standard")
    return {"slug": slug, "name": row.get("name"), "reset": True,
            "admin_username": result.get("admin_username"),
            "admin_password": result.get("admin_password")}


# Days a tenant keeps working after their trial or licence end date. A customer
# whose bank transfer clears on the 3rd should not lose their books on the 1st,
# and chasing a renewal is a conversation, not an outage. Set to 0 to cut access
# on the date itself.
LICENCE_GRACE_DAYS = int(os.environ.get("LICENCE_GRACE_DAYS", "7") or 7)


def expire_due_licences(grace_days: int = None) -> list:
    """Suspend tenants whose TRIAL or LICENCE ended more than the grace period
    ago. Returns what changed.

    Both dates are checked. Only `trial_ends_at` used to be, so a paid customer
    whose `license_expires_at` passed kept full access indefinitely — the field
    was written at provisioning, shown in the console, and then never consulted
    by anything.

    Suspend, never delete: the customer keeps their data, so taking a renewal is
    flipping the status back. Suspension is the existing 402 path, so nothing
    new has to be taught to the request layer.

    Idempotent — an already-suspended tenant is skipped, so running it on every
    flush cycle costs one indexed query and changes nothing.
    """
    from utils import _now
    from datetime import date, timedelta
    grace = LICENCE_GRACE_DAYS if grace_days is None else grace_days
    # Compared as ISO dates (YYYY-MM-DD), which sort lexicographically.
    cutoff = (date.today() - timedelta(days=max(0, grace))).isoformat()
    raw = _connect()
    try:
        ensure_tenants_catalog(raw)
        with raw.cursor() as cur:
            cur.execute(
                "UPDATE public.tenants SET status='suspended', updated_at=%s "
                "WHERE status='active' AND ("
                "      (trial_ends_at      IS NOT NULL AND trial_ends_at      < %s)"
                "   OR (license_expires_at IS NOT NULL AND license_expires_at < %s)"
                ") "
                "RETURNING slug, name, trial_ends_at, license_expires_at",
                (_now(), cutoff, cutoff))
            changed = [dict(r) for r in cur.fetchall()]
        raw.commit()
    finally:
        raw.close()
    for row in changed:
        _CACHE.pop(row["slug"], None)
        _SCHEMA_STATUS.pop(schema_for_slug(row["slug"]), None)
        _LICENCE_CACHE.pop(schema_for_slug(row["slug"]), None)
        _LICENCE_CACHE.pop(("seats", schema_for_slug(row["slug"])), None)
    return changed


