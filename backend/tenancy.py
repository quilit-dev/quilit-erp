expire_due_trials = expire_due_licences


_LICENCE_CACHE = {}          # schema -> (cached_at, payload)
_LICENCE_TTL   = 300         # 5 min; a renewal shows up within one cache cycle


def tenant_licence_status(schema: str) -> dict:
    """What the CUSTOMER is allowed to know about their own licence.

    The dates live in `public.tenants`, which the tenant's own schema cannot
    see, so without this the business had no way to learn it was about to be
    suspended — the first sign was being locked out. That is a bad way to find
    out, and an avoidable support call.

    Deliberately narrow: days remaining and whether the grace period has begun.
    Not the plan, the seat count, the price or the notes — those are the
    operator's commercial record, not the customer's business.
    """
    from datetime import date
    hit = _LICENCE_CACHE.get(schema)
    if hit is not None:
        cached_at, value = hit
        if (time.monotonic() - cached_at) < _LICENCE_TTL:
            return value

    payload = {"applicable": False}
    try:
        raw = _connect()
    except Exception:
        return payload                   # never block a page over a banner
    try:
        with raw.cursor() as cur:
            cur.execute(
                "SELECT status, trial_ends_at, license_expires_at "
                "FROM public.tenants WHERE schema_name=%s", (schema,))
            row = cur.fetchone()
    except Exception:
        return payload
    finally:
        raw.close()

    if row:
        def _left(value):
            if not value:
                return None
            try:
                y, m, d = (int(p) for p in str(value)[:10].split("-"))
                return (date(y, m, d) - date.today()).days
            except Exception:
                return None

        # Whichever ends sooner governs: a licence running to next year is no
        # comfort if the trial it sits inside has already lapsed.
        candidates = [(k, _left(row.get(k)))
                      for k in ("trial_ends_at", "license_expires_at")]
        candidates = [(k, v) for k, v in candidates if v is not None]
        if candidates:
            kind, days = min(candidates, key=lambda kv: kv[1])
            payload = {
                "applicable":  True,
                "kind":        "trial" if kind == "trial_ends_at" else "licence",
                "days_left":   days,
                "expires_at":  str(row.get(kind))[:10],
                "in_grace":    days < 0,
                "grace_days":  LICENCE_GRACE_DAYS,
                "status":      row.get("status"),
            }

    _LICENCE_CACHE[schema] = (time.monotonic(), payload)
    return payload


def tenant_seat_limit(schema: str):
    """Licensed seats for a schema, or None for unlimited / not applicable.

    Shares the licence cache: it is read on every login, and an uncached lookup
    would put a cross-schema query in front of the one request a customer
    notices most.
    """
    hit = _LICENCE_CACHE.get(("seats", schema))
    if hit is not None:
        cached_at, value = hit
        if (time.monotonic() - cached_at) < _LICENCE_TTL:
            return value

    limit = None
    try:
        raw = _connect()
    except Exception:
        return None                      # fail open: never lock a customer out
    try:                                 # over an infrastructure hiccup
        with raw.cursor() as cur:
            cur.execute("SELECT max_users FROM public.tenants WHERE schema_name=%s",
                        (schema,))
            row = cur.fetchone()
            if row and row.get("max_users"):
                limit = int(row["max_users"])
    except Exception:
        return None
    finally:
        raw.close()

    _LICENCE_CACHE[("seats", schema)] = (time.monotonic(), limit)
    return limit


def tenant_modules(schema: str):
    """Effective (dependency-closed) module set for a schema, or None when the
    tenant has no explicit licence and should see everything.

    Cached: this is consulted on every permission check, so an uncached lookup
    would put a query in front of every request.

    The cache is per-PROCESS, and production runs WEB_CONCURRENCY>1. Popping on
    write therefore only corrects the worker that handled the write; the others
    would keep serving the old licence until restart. So entries also expire:
    an operator upgrading a customer sees it take effect everywhere within
    _MODULES_TTL rather than "sometimes, depending which worker answers".
    """
    hit = _MODULES_CACHE.get(schema)
    if hit is not None:
        cached_at, value = hit
        if (time.monotonic() - cached_at) < _MODULES_TTL:
            return value
    try:
        raw = _connect()
    except Exception:
        return None                      # fail open rather than lock everyone out
    try:
        with raw.cursor() as cur:
            cur.execute("SELECT modules FROM public.tenants WHERE schema_name=%s",
                        (schema,))
            row = cur.fetchone()
    except Exception:
        return None
    finally:
        raw.close()
    raw_modules = (row or {}).get("modules") if row else None
    if not raw_modules:
        result = None                    # unlicensed == unrestricted (dev/demo)
    else:
        import capabilities
        result = capabilities.resolve(
            {m.strip() for m in raw_modules.split(",") if m.strip()})
    _MODULES_CACHE[schema] = (time.monotonic(), result)
    return result


