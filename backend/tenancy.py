def _no_workspace_response(scope):
    """404 for an unknown subdomain, in whichever format the caller can use."""
    from starlette.responses import HTMLResponse, JSONResponse
    headers = {k.decode("latin1").lower(): v.decode("latin1")
               for k, v in scope.get("headers", [])}
    accept = headers.get("accept", "")
    detail = "No such workspace. Check the address with your administrator."
    # /api callers and anything explicitly asking for JSON keep the old body,
    # so nothing that parses this response has to change.
    if scope.get("path", "").startswith("/api") or "application/json" in accept:
        return JSONResponse({"detail": detail}, status_code=404)
    if "text/html" not in accept:
        return JSONResponse({"detail": detail}, status_code=404)
    host = headers.get("host", "").split(":")[0].strip()
    # Escape: the host is attacker-controllable, and it is echoed into markup.
    from html import escape
    return HTMLResponse(_NO_WORKSPACE_HTML.format(host=escape(host)),
                        status_code=404)


class TenantMiddleware:
    """Pure-ASGI middleware: resolve the request's tenant schema and stash it in
    the ContextVar so get_db can pin the connection's search_path. A request that
    resolves to a SUSPENDED tenant is blocked with 402. Inert unless
    TENANCY=schema."""

    def __init__(self, app):
        self.app = app

    async def __call__(self, scope, receive, send):
        if scope.get("type") != "http" or not IS_SCHEMA_TENANCY:
            await self.app(scope, receive, send)
            return
        resolved = resolve_tenant_from_scope(scope)
        if resolved is not None and resolved[1] != "active":
            from starlette.responses import JSONResponse
            await JSONResponse(
                {"detail": "This workspace is suspended. Please contact support."},
                status_code=402)(scope, receive, send)
            return
        if resolved is None and _looks_like_tenant_host(scope):
            # A subdomain of OUR base domain that matches no tenant. Without
            # this the wildcard DNS record quietly serves the app for any
            # typo'd hostname, so a mistyped workspace looks like a working
            # ERP the user cannot log into.
            await _no_workspace_response(scope)(scope, receive, send)
            return
        schema = resolved[0] if resolved else None
        token = set_current_schema(schema)
        try:
            await self.app(scope, receive, send)
        finally:
            reset_current_schema(token)


def upgrade_all_tenant_schemas() -> dict:
    """Apply the post-baseline upgrade to EVERY existing tenant schema.

    Each customer owns a full copy of the tables, so adding a column to
    `_ensure_pg_post_baseline` reaches only two places on its own: the `public`
    schema (upgraded on boot, with the default search_path) and any tenant
    provisioned afterwards. A schema created BEFORE the column was added never
    receives it, and the failure appears as a 500 on the first write — which is
    exactly how invoice creation broke for a live customer while `public` had
    the column and every test passed.

    Runs on boot, after the public upgrade. Idempotent: every statement in the
    post-baseline is ADD COLUMN IF NOT EXISTS / CREATE IF NOT EXISTS, so this is
    a no-op once a schema is current.

    One tenant failing must not stop the others or block startup, so each is
    attempted independently and the outcome is returned for logging rather than
    raised.
    """
    if not IS_SCHEMA_TENANCY:
        return {"skipped": "single-tenant mode"}

    from database import _ensure_pg_post_baseline
    out = {"upgraded": [], "failed": {}}
    try:
        raw = _connect()
    except Exception as e:
        return {"failed": {"connect": str(e)}}
    try:
        ensure_tenants_catalog(raw)
        with raw.cursor() as cur:
            cur.execute("SELECT slug, schema_name FROM public.tenants ORDER BY id")
            tenants = [dict(r) for r in cur.fetchall()]

        for t in tenants:
            schema = t["schema_name"]
            if not valid_schema_name(schema):
                out["failed"][t["slug"]] = f"unsafe schema name {schema!r}"
                continue
            try:
                with raw.cursor() as cur:
                    cur.execute(f'SET search_path TO "{schema}", public')
                _ensure_pg_post_baseline(raw)
                out["upgraded"].append(t["slug"])
            except Exception as e:
                raw.rollback()
                out["failed"][t["slug"]] = str(e)[:200]
        # Leave the connection pointing somewhere harmless.
        try:
            with raw.cursor() as cur:
                cur.execute("SET search_path TO public")
            raw.commit()
        except Exception:
            pass
    finally:
        raw.close()
    return out
